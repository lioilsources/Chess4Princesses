// Reads the board colours straight from the Flutter widgets (they import dart:ui,
// so the Dart VM can't run them): each entry is a regex whose first group is the
// 0xAARRGGBB literal. Used by gen-palette.ts and test/palette-sync.test.ts.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));

const SOURCES: Record<string, [file: string, pattern: RegExp]> = {
  light: ['lib/features/board/chess_board.dart', /static const light = Color\(0x([0-9A-Fa-f]{8})\)/],
  dark: ['lib/features/board/chess_board.dart', /static const dark = Color\(0x([0-9A-Fa-f]{8})\)/],
  frame: ['lib/features/board/chess_board.dart', /static const frame = Color\(0x([0-9A-Fa-f]{8})\)/],
  done: ['lib/features/board/chess_board.dart', /m\.done\.contains\(s\)\) Container\(color: const Color\(0x([0-9A-Fa-f]{8})\)/],
  selected: ['lib/features/board/chess_board.dart', /m\.selected == s\) Container\(color: const Color\(0x([0-9A-Fa-f]{8})\)/],
  candidate: ['lib/features/board/chess_board.dart', /candidate\.isNotEmpty\) Container\(color: const Color\(0x([0-9A-Fa-f]{8})\)/],
  star: ['lib/features/board/chess_board.dart', /Icons\.star_rounded, size: size \* \.8, color: const Color\(0x([0-9A-Fa-f]{8})\)/],
  dot: ['lib/features/board/chess_board.dart', /color: piece == null \? const Color\(0x([0-9A-Fa-f]{8})\) : null/],
  dotRing: ['lib/features/board/chess_board.dart', /Border\.all\(color: const Color\(0x([0-9A-Fa-f]{8})\), width: size \* \.07\)/],
  plateMine: ['lib/features/board/piece_token.dart', /mine \? const Color\(0x([0-9A-Fa-f]{8})\)/],
  plateTheirs: ['lib/features/board/piece_token.dart', /mine \? const Color\(0x[0-9A-Fa-f]{8}\) : const Color\(0x([0-9A-Fa-f]{8})\)/],
  background: ['lib/features/lesson/lesson_screen.dart', /backgroundColor: const Color\(0x([0-9A-Fa-f]{8})\)/],
};

/** 0xAARRGGBB → '#RRGGBB' when opaque, else 'rgba(r, g, b, a)'. */
export function css(argb: string): string {
  const n = Number.parseInt(argb, 16);
  const a = (n >>> 24) & 255;
  const rgb = (n & 0xffffff).toString(16).toUpperCase().padStart(6, '0');
  if (a === 255) return `#${rgb}`;
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${Number((a / 255).toFixed(3))})`;
}

export function dartPalette(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [name, [file, re]] of Object.entries(SOURCES)) {
    const m = re.exec(readFileSync(root + file, 'utf8'));
    if (!m) throw new Error(`${name}: pattern not found in ${file} (Dart changed? update scripts/dart-palette.ts)`);
    out[name] = css(m[1]);
  }
  return out;
}

export function renderPalette(p: Record<string, string>): string {
  const body = Object.entries(p).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
  return `// Generated by scripts/gen-palette.ts from the Flutter board widgets. Do not edit.\n// test/palette-sync.test.ts fails when the Dart colours change: run npm run gen.\nexport const DART_PALETTE = {\n${body}\n} as const;\n`;
}
